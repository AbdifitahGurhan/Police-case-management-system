const cleanStr = (str) =>
  String(str || '')
    .toLowerCase()
    .replace(/\bregion\b|\bgobolka\b|\bstate\b|\badministration\b/g, '')
    .replace(/[^a-z0-9]/g, '')
    .trim();

export function getDistrictsForRegion(regionObjOrName) {
  if (!regionObjOrName) return [];

  const candidates = typeof regionObjOrName === 'string'
    ? [regionObjOrName]
    : [
        regionObjOrName.region_name,
        regionObjOrName.name,
        regionObjOrName.region_code,
        regionObjOrName.code,
      ].filter(Boolean);

  for (const key of candidates) {
    if (DISTRICTS_BY_REGION[key]) {
      return DISTRICTS_BY_REGION[key];
    }
  }

  for (const key of candidates) {
    const cleanK = cleanStr(key);
    if (!cleanK) continue;
    for (const [mapKey, val] of Object.entries(DISTRICTS_BY_REGION)) {
      if (cleanStr(mapKey) === cleanK) {
        return val;
      }
    }
  }

  return [];
}
